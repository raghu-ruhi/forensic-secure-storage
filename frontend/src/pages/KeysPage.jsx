import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { listEvidence, rotateEvidenceKey } from "../api/endpoints";
import Alert from "../components/Alert";

export default function KeysPage() {
  const [evidence, setEvidence] = useState([]);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState("");
  const [busyId, setBusyId] = useState(null);
  const [loading, setLoading] = useState(true);

  function load() {
    listEvidence()
      .then((res) => setEvidence(res.data))
      .catch((err) => setError(err.response?.data?.error || "Failed to load evidence"))
      .finally(() => setLoading(false));
  }

  useEffect(load, []);

  async function handleRotate(id) {
    setBusyId(id);
    setError("");
    setSuccess("");
    try {
      await rotateEvidenceKey(id);
      setSuccess("Encryption key rotated successfully.");
      load();
    } catch (err) {
      setError(err.response?.data?.error || "Key rotation failed");
    } finally {
      setBusyId(null);
    }
  }

  return (
    <div>
      <h1 className="text-2xl font-bold text-slate-900 mb-1">Encryption Keys</h1>
      <p className="text-sm text-slate-500 mb-6">
        Every evidence file has its own AES-256 key, generated by an EEO-inspired
        optimizer and wrapped under a master key. Rotate a key to re-encrypt a file
        under a freshly generated key.
      </p>

      <Alert type="error">{error}</Alert>
      <Alert type="success">{success}</Alert>

      <div className="bg-white border border-slate-200 rounded-xl overflow-hidden">
        {loading ? (
          <p className="p-4 text-sm text-slate-500">Loading...</p>
        ) : evidence.length === 0 ? (
          <p className="p-4 text-sm text-slate-500">No evidence uploaded yet.</p>
        ) : (
          <table className="w-full text-sm">
            <thead className="bg-slate-50 text-slate-500 text-left">
              <tr>
                <th className="px-4 py-2 font-medium">Case / Title</th>
                <th className="px-4 py-2 font-medium">Key Record ID</th>
                <th className="px-4 py-2 font-medium"></th>
              </tr>
            </thead>
            <tbody>
              {evidence.map((e) => (
                <tr key={e.id} className="border-t border-slate-100">
                  <td className="px-4 py-2">
                    <Link to={`/evidence/${e.id}`} className="text-blue-600 hover:underline">
                      {e.case_number}
                    </Link>
                    <p className="text-xs text-slate-500">{e.title}</p>
                  </td>
                  <td className="px-4 py-2 font-mono text-xs text-slate-500">
                    {e.id.slice(0, 8)}...
                  </td>
                  <td className="px-4 py-2">
                    <button
                      onClick={() => handleRotate(e.id)}
                      disabled={busyId === e.id}
                      className="text-xs bg-slate-100 hover:bg-slate-200 disabled:opacity-60 text-slate-700 px-2.5 py-1 rounded-md"
                    >
                      {busyId === e.id ? "Rotating..." : "Rotate Key"}
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>
    </div>
  );
}
